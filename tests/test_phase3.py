"""Phase 3: Mardia, MANOVA.RM (WTS/MATS), HE matrices, DISTATIS and CDPCA
against R (fixtures/phase3.json, generated by fixtures/make_phase3.R)."""
import json
from pathlib import Path

import numpy as np
import pytest

from biplotpy import load_iris
from biplotpy.cdpca import cdpca
from biplotpy.distatis import distatis
from biplotpy.multitest import he_ellipses, he_matrices, manova_wts, mardia, roy_crit

F = json.loads((Path(__file__).parent / "fixtures" / "phase3.json").read_text())
A = lambda x: np.array(x, float)


def align(P, R):
    P = A(P).copy()
    for k in range(P.shape[1]):
        if np.sum(P[:, k] * R[:, k]) < 0:
            P[:, k] *= -1
    return P


def close(a, b, tol=1e-9):
    np.testing.assert_allclose(A(a), A(b), atol=tol, rtol=0)


def test_mardia_matches_psych():
    ir = load_iris()
    m = mardia(ir.iloc[:, :4].to_numpy()); r = F["mardia"]["iris"]
    for a, b in [("b1p", "b1p"), ("b2p", "b2p"), ("skew", "skew"), ("small_skew", "small.skew"),
                 ("p_skew", "p.skew"), ("p_small", "p.small"), ("kurtosis", "kurtosis"), ("p_kurt", "p.kurt")]:
        close(m[a], r[b], 1e-10)
    r = F["mardia"]["exp"]; m = mardia(A(r["X"]))
    close(m["b1p"], r["b1p"]); close(m["kurtosis"], r["kurtosis"])


def test_manova_wts_mats_match_manova_rm():
    f = F["manova"]
    for res, pr in (("paramBS", f["p_param"]), ("WildBS", f["p_wild"])):
        m = manova_wts(A(f["Y"]), f["g"], iter=20000, seed=7, resampling=res)
        close(m["WTS"], f["WTS"][0]); assert m["df"] == f["WTS"][1]; close(m["p_WTS_chisq"], f["WTS"][2])
        close(m["MATS"], f["MATS"])
        # bootstrap p-values: different RNG; agreement within 4 Monte Carlo SE
        for mine, theirs in ((m["p_WTS_boot"], pr[0]), (m["p_MATS_boot"], pr[1])):
            se = np.sqrt(2 * theirs * (1 - theirs) / 20000)
            assert abs(mine - theirs) < 4 * se


def test_manova_mats_size_under_heteroscedasticity():
    """Unequal covariances and sizes: the parametric bootstrap MATS keeps its size."""
    rng = np.random.default_rng(3)
    rej = []
    for s in range(60):
        Y = np.vstack([rng.normal(0, 1, (10, 3)), rng.normal(0, 3, (25, 3)), rng.normal(0, 0.5, (8, 3))])
        g = ["a"] * 10 + ["b"] * 25 + ["c"] * 8
        rej.append(manova_wts(Y, g, iter=300, seed=rng)["p_MATS_boot"] < 0.05)
    assert np.mean(rej) < 0.15


def test_he_matrices_match_car():
    ir = load_iris()
    he = he_matrices(ir.iloc[:, :4].to_numpy(), ir.iloc[:, 4]); f = F["he"]
    close(he["H"], f["H"], 1e-9); close(he["E"], f["E"], 1e-9)
    close(list(he["stats"].values()), f["stats"], 1e-10)
    close(roy_crit(0.05, 4, 2, 147), f["roy"], 1e-12)
    e = he_ellipses(ir.iloc[:, :4].to_numpy(), ir.iloc[:, 4])
    assert e["roy_significant"] and e["H"].shape == (61, 2)


@pytest.mark.parametrize("norm", ["MFA", "SUMPCA", "NUCLEAR"])
def test_distatis_matches_distatisr(norm):
    f = F["distatis"]; r = f[norm]
    d = distatis(np.stack([A(c) for c in f["cube"]], 2), norm=norm)
    # NUCLEAR: DistatisR keeps eigenvalues > 2 eps, so a numerically zero eigenvalue
    # can enter the norm; agreement is then ~1e-8.
    tol = 1e-6 if norm == "NUCLEAR" else 1e-12
    close(d["C"], r["C"], 1e-12); close(d["alpha"], r["alpha"], 1e-12)
    close(d["Splus"], r["Splus"], tol); close(d["eig_Splus"], r["eig"], tol)
    R = A(r["F"]); close(align(d["F"], R), R, tol)
    R = A(r["partial1"]); close(align(d["partial_F"][:, :, 0], R), R, max(tol, 1e-10))


def test_cdpca_matches_biplotbootgui_from_same_start():
    f = F["cdpca"]
    c = cdpca(A(f["X"]), 3, 2, init=(A(f["U0"]), A(f["V0"])))
    close(c["F"], f["F"], 1e-9); close(c["U"], f["U"], 0); close(c["V"], f["V"], 0)
    R = A(f["A"]); close(align(c["A"], R), R, 1e-10)
    assert c["iter"] == f["iter"]
    close(c["bcdev"], f["bcdev"], 1e-9); close(c["Enorm"], f["Enorm"], 1e-12)


def test_cdpca_recovers_clusters_and_variable_groups():
    from itertools import permutations
    f = F["cdpca"]
    c = cdpca(A(f["X"]), 3, 2, nstart=20, seed=1)
    truth = np.array(f["truth"])
    acc = max(np.mean(np.array(p)[c["cluster"] - 1] == truth) for p in permutations([1, 2, 3]))
    assert acc > 0.9
    groups = c["V"].argmax(1)
    assert groups[0] == groups[1] == groups[2] and groups[3] == groups[4] == groups[5] and groups[0] != groups[3]
