def test_binary_biplot_reaches_r_optimum():
    f = F["binary"]
    b = bp.binary_logistic_biplot(A_(f["X"]), penalization=f["lambda"], init=A_(f["A0"]))
    assert b.objective <= f["value"] + 1e-6
    eta = b.B[:, 0] + b.A @ b.B[:, 1:].T
    close(eta, A_(f["eta"]), 1e-3)


def test_binary_biplot_consistency():
    """Recovery of the true probabilities improves as rows and columns grow."""
    out = []
    for n, p in [(60, 8), (300, 60)]:
        rng = np.random.default_rng(0)
        A = rng.normal(size=(n, 2)); B = rng.normal(0, 1.5, size=(p, 2)); b0 = rng.normal(0, .5, p)
        P = expit(b0 + A @ B.T)
        X = (rng.random((n, p)) < P).astype(float)
        r = bp.binary_logistic_biplot(X, penalization=1)
        out.append(np.corrcoef(r.fitted.ravel(), P.ravel())[0, 1])
    assert out[1] > out[0] and out[1] > 0.95
