"""Phase 2 of biplotpy: STATIS family, unfolding, GGE, AMMI and logistic
biplots, against R references (tests/fixtures/phase2.json, generated by
fixtures/make_phase2.R) and by simulated recovery."""
import json
from pathlib import Path

import numpy as np
import pytest
from scipy.linalg import orthogonal_procrustes
from scipy.special import expit

import biplotpy as bp

F = json.loads((Path(__file__).parent / "fixtures" / "phase2.json").read_text())
A_ = lambda x: np.array([[np.nan if v == "NA" else v for v in r] for r in x], float) if isinstance(x[0], list) else np.array(x, float)


def align(P, R):
    P = np.array(P, float).copy()
    for k in range(P.shape[1]):
        if np.sum(P[:, k] * R[:, k]) < 0:
            P[:, k] *= -1
    return P


def close(a, b, tol=1e-9):
    np.testing.assert_allclose(np.asarray(a, float), np.asarray(b, float), atol=tol, rtol=0)


# ----------------------------------------------------------------- STATIS family
def test_statis_matches_multbiplotr_and_ade4():
    f = F["statis"]
    s = bp.statis({k: A_(v) for k, v in f["X"].items()})
    close(s.RV.values, A_(f["RV"])); close(s.RV.values, A_(f["RV_ade4"]))
    close(s.weights, f["weights"]); close(s.eigenvalues, f["eig"]); close(s.eig_inter, f["eiginter"])
    R = A_(f["rows"]); close(align(s.row_coordinates, R), R)
    C = A_(f["cols"]); close(align(s.col_coordinates, C), C)
    close(s.scale_factor, f["scf"])
    T = A_(f["traj1"]); close(align(np.array([t[0] for t in s.trajectories]), T), T)


def test_canonical_statis_matches_multbiplotr():
    f = F["canstatis"]
    c = bp.canonical_statis({k: A_(v) for k, v in f["X"].items()}, f["groups"])
    close(c.RV.values, A_(f["RV"])); close(c.weights, f["weights"]); close(c.eigenvalues, f["eig"])
    R = A_(f["rows"]); close(align(c.row_coordinates, R), R)
    C = A_(f["cols"]); close(align(c.col_coordinates, C), C)
    close(c.scale_factor, f["scf"])


def test_dual_statis_core_matches_multbiplotr():
    f = F["dualstatis"]
    assert f["error"] != "no error"          # MultBiplotR::DualStatisBiplot is unfinished
    d = bp.dual_statis({k: A_(v) for k, v in f["X"].items()})
    close(d.common_sd, f["sd"]); close(d.RV.values, A_(f["RV"])); close(d.weights, f["weights"])
    close(d.eigenvalues, A_(f["eig"])[:len(d.eigenvalues)])
    C = A_(f["cols"]); close(align(d.col_coordinates, C), C)


def test_statis_recovers_common_structure():
    """Tables generated from a common configuration plus noise: RV near 1 for the
    signal tables, the pure-noise table gets the smallest weight, and the
    compromise reproduces the common configuration."""
    rng = np.random.default_rng(3)
    n = 40
    Z = rng.normal(size=(n, 2)) * [3, 2]
    tabs = {f"T{t}": Z @ rng.normal(size=(2, 5)) + rng.normal(scale=0.3, size=(n, 5)) for t in range(4)}
    tabs["noise"] = rng.normal(size=(n, 5))
    s = bp.statis(tabs)
    assert np.argmin(s.weights) == 4
    assert s.RV.values[:4, :4].min() > 0.8
    Zs = (Z - Z.mean(0))
    R, _ = orthogonal_procrustes(s.row_coordinates, Zs)
    assert np.corrcoef((s.row_coordinates @ R).ravel(), Zs.ravel())[0, 1] > 0.95


# ----------------------------------------------------------------- dynamic biplot
def test_dynamic_biplot_algebra():
    rng = np.random.default_rng(5)
    base = rng.normal(size=(15, 4))
    occ = [base + 0.3 * t + rng.normal(scale=0.2, size=base.shape) for t in range(4)]
    for alpha in (2, 1, 0):
        r = bp.dynamic_biplot(occ, reference=2, alpha=alpha)
        close(r["row_coordinates"]["t3"], r["reference"].row_coordinates, 1e-10)
        close(r["col_coordinates"]["t3"], r["reference"].col_coordinates, 1e-10)
        m = bp.dynamic_biplot(occ, reference="mean", alpha=alpha)
        close(np.mean(m["trajectories"], axis=1), m["reference"].row_coordinates, 1e-10)
    assert (r["quality"].values <= 100 + 1e-9).all()


# ----------------------------------------------------------------- unfolding
def test_unfolding_matches_smacof():
    f = F["unfolding"]
    u = bp.unfolding(A_(f["delta"]))
    assert u["niter"] == f["niter"]
    close(u["stress"], f["stress"], 1e-12)
    for k in ("conf_row", "conf_col"):
        R = A_(f[k]); close(align(u[k], R), R, 1e-9)
    close(u["confdist"], A_(f["confdist"]), 1e-9)


def test_unfolding_recovers_exact_configuration():
    rng = np.random.default_rng(11)
    x, y = rng.normal(size=(25, 2)), rng.normal(size=(8, 2))
    D = np.sqrt(((x[:, None] - y[None]) ** 2).sum(2))
    u = bp.unfolding(D, eps=1e-10)
    assert u["stress"] < 1e-3
    Z = np.vstack([x, y]); Zh = np.vstack([u["conf_row"], u["conf_col"]])
    Z0, Zh0 = Z - Z.mean(0), Zh - Zh.mean(0)
    R, sc = orthogonal_procrustes(Zh0, Z0)
    fit = Zh0 @ R * (np.sum(Z0 * (Zh0 @ R)) / np.sum((Zh0 @ R) ** 2))
    assert np.abs(fit - Z0).max() < 0.05


# ----------------------------------------------------------------- GGE and AMMI
@pytest.mark.parametrize("key", [k for k in F["gge"] if k != "data"])
def test_gge_matches_ggebiplots(key):
    svp, cen = key.split("_")
    v = F["gge"][key]
    m = bp.gge_model(A_(F["gge"]["data"]), centering=cen, scaling="sd", svp=svp)
    G, E = A_(v["G"])[:, :2], A_(v["E"])[:, :2]   # dims 1-2 (a null dimension is arbitrary)
    close(align(m["coordgenotype"][:, :2], G), G); close(align(m["coordenviroment"][:, :2], E), E)
    close(m["eigenvalues"][:len(v["d"])], v["d"])


def test_ammi_matches_agricolae():
    f = F["ammi"]
    a = bp.ammi(f["env"], f["gen"], f["rep"], f["y"])
    close(a["anova"].iloc[:, :4].values, A_(f["anova"]), 1e-7)
    An = A_(f["analysis"])
    close(a["analysis"][["Df", "Sum Sq"]].values, An[:, [2, 3]], 1e-6)
    close(a["analysis"]["percent"].values, An[:, 0], 0.051)    # agricolae rounds to 1 decimal
    G = [b for b in f["biplot"] if b["type"].strip() == "GEN"]
    Rg = np.array([[b[f"PC{k}"] for k in range(1, 6)] for b in G])
    Pg = a["genotype_scores"].loc[[b["_row"] for b in G]].values[:, :5]
    close(align(Pg, Rg), Rg, 1e-10)


